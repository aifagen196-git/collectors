// collectors/verifyRipplingBoards.js
//
// Builds config/ripplingCompanies.js. Rippling has no public list of the
// companies using its job boards, so this takes every company slug from the
// other collectors' config/*Companies.js lists (plus the current Rippling
// list) and keeps the ones whose public board answers with at least one job:
//
//   GET https://api.rippling.com/platform/api/ats/v1/board/{slug}/jobs
//   -> 200 with a JSON array of jobs, or 404 when the board doesn't exist
//
//   node collectors/verifyRipplingBoards.js
//
// Re-run it now and then to pick up new companies and drop closed boards.

import axios from "axios";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const dir = path.dirname(fileURLToPath(import.meta.url));
const CONFIG_DIR = path.join(dir, "config");
const OUT = path.join(CONFIG_DIR, "ripplingCompanies.js");
const CONCURRENCY = Number(process.env.VERIFY_CONCURRENCY || 4);
const UA = "AIFAGenJobCollector/1.0 (+https://aifagenlabs.com)";

const toSlug = (s) =>
  String(s).toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

async function candidateSlugs() {
  const slugs = new Set();
  for (const f of fs.readdirSync(CONFIG_DIR).filter((f) => /Companies\.js$/.test(f))) {
    let list;
    try {
      const m = await import(pathToFileURL(path.join(CONFIG_DIR, f)).href);
      list = m.default || Object.values(m)[0];
    } catch {
      continue;
    }
    if (!Array.isArray(list)) continue;
    for (const x of list) {
      for (const c of [typeof x === "string" ? x : null, x?.slug, x?.board, x?.token, x?.company, x?.name]) {
        if (!c) continue;
        const s = toSlug(c);
        if (s && s.length < 40) slugs.add(s);
        // "Acme Inc" -> also try "acme"
        const first = s.split("-")[0];
        if (first && first.length > 2) slugs.add(first);
      }
    }
  }
  return [...slugs].sort();
}

async function check(slug) {
  try {
    const res = await axios.get(
      `https://api.rippling.com/platform/api/ats/v1/board/${slug}/jobs`,
      { timeout: 15000, validateStatus: null, headers: { "User-Agent": UA } },
    );
    if (res.status === 200 && Array.isArray(res.data)) return res.data.length;
    if (res.status === 429) return "rate-limited";
    return 0;
  } catch {
    return 0;
  }
}

async function main() {
  const slugs = await candidateSlugs();
  console.log(`Checking ${slugs.length} candidate slugs against Rippling...`);
  const alive = [];
  let i = 0;
  let checked = 0;
  let limited = 0;
  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (i < slugs.length) {
        const slug = slugs[i++];
        const n = await check(slug);
        checked++;
        if (n === "rate-limited") limited++;
        else if (n > 0) {
          alive.push({ slug, jobs: n });
          console.log(`  ✅ ${slug}: ${n} jobs`);
        }
        if (checked % 250 === 0) console.log(`  ...${checked}/${slugs.length}`);
      }
    }),
  );
  alive.sort((a, b) => a.slug.localeCompare(b.slug));

  const body = `// collectors/config/ripplingCompanies.js
//
// Rippling job-board slugs (https://ats.rippling.com/{slug}/jobs), generated by
// collectors/verifyRipplingBoards.js on ${new Date().toISOString().slice(0, 10)}. Each one answered
// with at least one job; the number is the job count at that time.

const companies = [
${alive.map((a) => `  "${a.slug}", // ${a.jobs}`).join("\n")}
];

export default companies;
`;
  fs.writeFileSync(OUT, body);
  const total = alive.reduce((s, a) => s + a.jobs, 0);
  console.log(`\n${alive.length} boards with jobs (${total} jobs). Rate-limited: ${limited}. Wrote ${OUT}`);
}

main();
